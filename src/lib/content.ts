type PortableTextBlock = {
  _type: 'block';
  _key: string;
  style: string;
  listItem?: 'bullet' | 'number';
  level?: number;
  markDefs: Array<{ _key: string; _type: 'link'; href: string }>;
  children: Array<{ _type: 'span'; _key: string; text: string; marks: string[] }>;
};

let blockCounter = 0;

function block(
  text: string,
  style = 'normal',
  listItem?: 'bullet' | 'number',
  marks: string[] = [],
  markDefs: PortableTextBlock['markDefs'] = [],
): PortableTextBlock {
  blockCounter += 1;
  return {
    _type: 'block',
    _key: `content-${blockCounter}`,
    style,
    ...(listItem ? { listItem, level: 1 } : {}),
    markDefs,
    children: [{ _type: 'span', _key: `span-${blockCounter}`, text, marks }],
  };
}

const p = (text: string) => block(text);
const h2 = (text: string) => block(text, 'h2');
const h3 = (text: string) => block(text, 'h3');
const li = (text: string) => block(text, 'normal', 'bullet');
const num = (text: string) => block(text, 'normal', 'number');
const quote = (text: string) => block(text, 'blockquote');
const linkParagraph = (text: string, href: string) => {
  blockCounter += 1;
  const key = `link-${blockCounter}`;
  return {
    _type: 'block' as const,
    _key: `content-${blockCounter}`,
    style: 'normal',
    markDefs: [{ _key: key, _type: 'link' as const, href }],
    children: [{ _type: 'span' as const, _key: `span-${blockCounter}`, text, marks: [key] }],
  };
};

